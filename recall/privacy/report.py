"""Render privacy/README.md from results/m7/redaction.json (every number in the README comes from that file).

PYTHONPATH=. .venv/bin/python -m recall.privacy.report          # rewrite privacy/README.md
PYTHONPATH=. .venv/bin/python -m recall.privacy.report --check  # exit 1 if README is stale
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

from recall.paths import REPO, RESULTS

RESULT = RESULTS / "m7" / "redaction.json"
README = REPO / "privacy" / "README.md"


def pct(m: dict[str, Any] | float | None) -> str:
    if m is None:
        return "–"
    if isinstance(m, dict):
        if m.get("point") is None:
            return "– (n=0)"
        lo, hi = m["ci95"]
        return f"{100 * m['point']:.1f}% [{100 * lo:.1f}, {100 * hi:.1f}]"
    return f"{100 * m:.1f}%"


def _bucket_label(k: str, unit: str) -> str:
    lo, hi = k.strip("[)").split(",")
    if float(hi) >= 10_000 and unit == "px":
        return f"≥ {lo} px"
    if float(hi) > 1 and unit == "frac":
        return f"≥ {100 * float(lo):.0f}% of image height"
    if unit == "frac":
        return f"{100 * float(lo):.0f}–{100 * float(hi):.0f}% of image height"
    if unit == "area":
        return (
            f"≥ {100 * float(lo):.0f}% of image area"
            if float(hi) > 1
            else f"{100 * float(lo):.0f}–{100 * float(hi):.0f}% of image area"
        )
    if unit == "textpx" and float(hi) >= 100:
        return f"≥ {lo} px"
    return f"{lo}–{hi} {'px' if unit in ('px', 'textpx') else ''}".strip()


def _table(rows: list[list[str]], header: list[str]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


def render(d: dict[str, Any]) -> str:
    cfg, f, s = d["config"], d["faces"], d["screens_documents"]
    cov = cfg["coverage_threshold"]
    fd, fu = f["recall"]["face_detector"], f["recall"]["full_redactor"]
    sd, su = s["recall"]["screen_detector"], s["recall"]["full_redactor"]
    fo, so = f["over_redaction"], s["over_redaction"]
    L: list[str] = []
    w = L.append
    w("# Privacy layer (M7): redaction results")
    w("")
    w("<!-- GENERATED by `python -m recall.privacy.report` from results/m7/redaction.json. Do not edit by hand. -->")
    w("")
    w(
        "Recall stores no video. Each event keeps at most one small thumbnail, and that thumbnail is redacted on the "
        "phone before it is written (`android/.../privacy/Redactor.kt`). This page reports how well that redactor "
        "works, measured on a desktop with a step-by-step Python port (`recall/privacy/redact.py`). What is and isn't "
        "protected overall is in [THREAT_MODEL.md](THREAT_MODEL.md)."
    )
    w("")
    w(
        f"- **Evidence stage:** `{d['evidence_stage']}` (desktop proxy, not measured on a phone). Commit "
        f"`{d['git_commit'][:10]}`{' (dirty tree)' if d['git_dirty'] else ''}, {d['timestamp']}."
    )
    fc = cfg["face_detector"]
    w(
        f"- **Redactor under test:** BlazeFace short-range ({fc['licence']}, sha256 `{fc['sha256'][:12]}…`), "
        f"score ≥ {fc['score_threshold']}, boxes padded by {100 * fc['box_padding']:.0f}%, no NMS. Then the "
        f"{cfg['screen_detector']['grid'][0]}×{cfg['screen_detector']['grid'][1]} screen/document grid heuristic "
        f"(bright cells, mean luma ≥ {cfg['screen_detector']['min_mean_luma']:.0f}, with ≥ "
        f"{100 * cfg['screen_detector']['min_edge_density']:.0f}% edge pixels). Each box is pixelated with "
        f"`{cfg['pixelate_block_px']}` px cells, and the result is downscaled to "
        f"{cfg['thumbnail'][0]}×{cfg['thumbnail'][1]}."
    )
    w(
        f"- **Metric:** a ground-truth region counts as *redacted* when ≥ {100 * cov:.0f}% of its area falls "
        f"inside the union of redaction boxes. Brackets are 95% bootstrap CIs ({cfg['n_bootstrap']} resamples), "
        "clustered by image."
    )
    w("")
    w("Reproduce:")
    w("")
    w("```")
    w("PYTHONPATH=. .venv/bin/python -m recall.privacy.assets face_detector wider_val   # sha256-verified downloads")
    w("PYTHONPATH=. .venv/bin/python -m recall.privacy.eval                            # -> results/m7/redaction.json")
    w("PYTHONPATH=. .venv/bin/python -m recall.privacy.report                          # -> this file")
    w("```")
    w("")

    # ------------------------------------------------------------------ faces
    ds = f["dataset"]
    w(f"## Faces: {ds['name']} {ds['split']} (not egocentric)")
    w("")
    w(f"> **Not egocentric data.** {ds['note']}")
    w("")
    w(
        f"{ds['n_images']} images and {ds['n_faces_valid']} valid faces{' (subsample)' if ds['subsampled'] else ''}. "
        f"Licence: {ds['licence']} Input: {f['protocol']['input']}."
    )
    w("")
    w(
        f"**Overall recall:** face detector {pct(fd['overall'])}; full redactor (faces + screen heuristic) "
        f"{pct(fu['overall'])}."
    )
    w("")
    w(
        "Recall by face height, in pixels and as a fraction of image height. BlazeFace squashes the whole image to "
        "128×128, so the fraction is what carries over to the device's event crops:"
    )
    w("")
    rows = [
        [_bucket_label(k, "px"), str(v["n"]), pct(v), pct(fu["by_face_height_px"][k])]
        for k, v in fd["by_face_height_px"].items()
    ]
    rows += [
        [_bucket_label(k, "frac"), str(v["n"]), pct(v), pct(fu["by_face_height_frac_of_image"][k])]
        for k, v in fd["by_face_height_frac_of_image"].items()
    ]
    w(_table(rows, ["face height", "faces", "recall: face detector", "recall: full redactor"]))
    w("")
    w("How recall depends on the coverage threshold:")
    w("")
    w(
        _table(
            [
                [f"≥ {100 * float(x):.0f}%", pct(v["face_detector"]), pct(v["full_redactor"])]
                for x, v in f["recall_vs_coverage_threshold"].items()
            ],
            ["coverage needed", "face detector", "full redactor"],
        )
    )
    w("")
    w("**Over-redaction** (mean over images):")
    w("")
    w(f"- image area pixelated by the face detector: {pct(fo['image_fraction_redacted_face_detector'])}")
    w(f"- image area pixelated by the screen heuristic: {pct(fo['image_fraction_redacted_screen_detector'])}")
    w(f"- image area pixelated in total: {pct(fo['image_fraction_redacted_full'])}")
    w(
        f"- non-face area pixelated (redaction outside any labelled face): {pct(fo['non_face_area_fraction_redacted_full'])}"
    )
    w(
        f"- images with at least one face box: {pct(fo['fraction_images_with_any_face_box'])}; mean raw boxes per "
        f"image (no NMS): {fo['mean_face_boxes_per_image_no_nms']:.2f}"
    )
    w("")
    w("Score-threshold sweep (face detector only; the app reads its threshold from `preprocess.faceThresh`):")
    w("")
    w(
        _table(
            [
                [f"{t['score_threshold']}", pct(t["recall"]), pct(t["image_fraction_redacted"])]
                for t in f["face_threshold_sweep"]
            ],
            ["score threshold", "recall", "image area pixelated"],
        )
    )
    w("")

    # ------------------------------------------------------------------ screens
    ds = s["dataset"]
    w("## Screens and documents: SYNTHETIC composites")
    w("")
    w(f"> **Synthetic data.** {ds['note']}")
    w("")
    w(
        f"{ds['n_images']} generated images (seed {ds['seed']}, digest `{ds['digest_sha256'][:12]}…`) with "
        f"{ds['n_positive_regions']} sensitive regions, {ds['n_distractor_regions']} text-free bright distractors, and "
        f"{ds['n_negative_only_images']} images that contain only distractors. Generator: `recall/privacy/synth.py`. "
        "No EPIC frames or photographs are used."
    )
    w("")
    w(f"**Overall recall:** screen heuristic {pct(sd['overall'])}; full redactor {pct(su['overall'])}.")
    w("")
    rows = [[k, str(v["n"]), pct(v), pct(su["by_kind"][k])] for k, v in sd["by_kind"].items()]
    w(_table(rows, ["kind", "regions", "recall: screen heuristic", "recall: full redactor"]))
    w("")
    rows = [[_bucket_label(k, "area"), str(v["n"]), pct(v)] for k, v in sd["by_area_frac_of_image"].items()]
    rows += [
        [f"glyph height {_bucket_label(k, 'textpx')}", str(v["n"]), pct(v)] for k, v in sd["by_text_height_px"].items()
    ]
    w(_table(rows, ["region size / text size", "regions", "recall: screen heuristic"]))
    w("")
    w(
        "Coverage-threshold sensitivity (full redactor): "
        + "; ".join(f"≥ {100 * float(x):.0f}%: {pct(v)}" for x, v in s["recall_vs_coverage_threshold"].items())
        + "."
    )
    w("")
    w("**Over-redaction:**")
    w("")
    w(f"- image area pixelated: {pct(so['image_fraction_redacted_full'])}")
    w(f"- non-sensitive area pixelated: {pct(so['non_sensitive_area_fraction_redacted_full'])}")
    w(
        f"- image area pixelated in images with no sensitive region: {pct(so['image_fraction_redacted_negative_only_images'])}"
    )
    w("")
    rows = [
        [k, str(v["n"]), pct(v), pct(v["mean_covered_fraction"])]
        for k, v in so["distractor_redacted_at_coverage"].items()
    ]
    w(
        _table(
            rows,
            ["distractor (no text)", "n", f"counted as redacted (≥ {100 * cov:.0f}% covered)", "mean area covered"],
        )
    )
    w("")

    # ------------------------------------------------------------------ caveats
    w("## Reading these numbers")
    w("")
    w(
        "- The face detector is a short-range model, and the redactor runs it once on the whole squashed crop. "
        "Recall depends mainly on how large the face is *relative to the crop*. Most WIDER faces are small crowd "
        "faces, which pulls the overall number down. The size-bucket rows are the ones to use when estimating "
        "egocentric behaviour, where bystanders are usually at conversational distance."
    )
    w(
        "- The screen heuristic only fires on bright cells, so dark-mode screens are by design not covered. A grid "
        "cell is flagged only if it is mostly text, so small or rotated regions rarely reach the coverage "
        "threshold. Most screen, document, and label content in this set passes through unredacted, and real "
        "footage is likely harder."
    )
    w(
        "- Port fidelity: the Python port uses a non-antialiased half-pixel bilinear resize (≈ Skia `filter=true`), "
        "float64 maths, and Pillow's JPEG encoder. Borderline detections can differ from the phone. The Kotlin "
        "sources it mirrors are pinned by sha256 in the result config (`port_of`)."
    )
    w("- See [THREAT_MODEL.md](THREAT_MODEL.md) §5 for the residual risks that redaction does not address.")
    w("")
    return "\n".join(L)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--result", type=Path, default=RESULT)
    a = ap.parse_args(argv)
    text = render(json.loads(a.result.read_text()))
    if a.check:
        ok = README.exists() and README.read_text() == text
        print(
            "privacy/README.md up to date" if ok else "privacy/README.md is stale: run python -m recall.privacy.report"
        )
        return 0 if ok else 1
    README.write_text(text)
    print(f"wrote {README}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

"""Synthetic e2e test clip: a hand puts a yellow "KEYS" object down on a brown "TABLE" (no real people, no EPIC data).

    .venv/bin/python android/tools/make_test_video.py   (or ./scripts/android_make_test_video.sh)

Writes android/app/src/androidTest/assets/e2e/keys_on_table.webm (VP8, 456×256, 10 fps, 16 s) plus a JSON sidecar
with the ground truth. Colours are fixed so the debug-only ColourKeyHandObject detector (androidTest) can stand in
for the HOI student, which cannot see a drawn hand:
  hand  = skin (224,172,140)   keys = yellow (255,215,0)   table = brown   counter = grey   sink = blue
Timeline: 0–2 s keys on the counter; 2–4 s hand reaches in; 4–9 s hand carries the keys to the table;
9–10 s keys set down on the table; 10–12 s hand withdraws; 12–16 s keys rest on the table.
"""

from __future__ import annotations

import json
import subprocess
import tempfile
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

W, H, FPS, DUR = 456, 256, 10, 16.0
OUT = Path(__file__).resolve().parents[1] / "app" / "src" / "androidTest" / "assets" / "e2e"
SKIN, KEYS, TABLE, COUNTER, SINK, WALL = (224, 172, 140), (255, 215, 0), (120, 72, 30), (150, 150, 150), (40, 90, 200), (235, 225, 205)
TABLE_BOX = (250, 150, 440, 240)
COUNTER_BOX = (16, 150, 200, 240)
SINK_BOX = (60, 60, 180, 120)


def lerp(a: float, b: float, u: float) -> float:
    return a + (b - a) * max(0.0, min(1.0, u))


def keys_pos(t: float) -> tuple[float, float]:
    """Centre of the keys."""
    start, end = (100.0, 185.0), (345.0, 185.0)
    if t < 4.0:
        return start
    if t < 9.0:  # carried along an arc
        u = (t - 4.0) / 5.0
        return lerp(start[0], end[0], u), lerp(start[1], end[1], u) - 50 * 4 * u * (1 - u)
    return end


def hand_pos(t: float) -> tuple[float, float] | None:
    """Centre of the hand (below-right of the keys while holding)."""
    if t < 2.0 or t >= 12.0:
        return None
    k = keys_pos(t)
    hold = (k[0] + 14, k[1] + 26)
    if t < 4.0:  # reach in from the bottom edge
        return lerp(hold[0], hold[0], 0), lerp(H + 40, hold[1], (t - 2.0) / 2.0)
    if t < 10.0:
        return hold
    return hold[0], lerp(hold[1], H + 60, (t - 10.0) / 2.0)  # withdraw


def frame(t: float, font) -> Image.Image:
    im = Image.new("RGB", (W, H), WALL)
    d = ImageDraw.Draw(im)
    d.rectangle(TABLE_BOX, fill=TABLE)
    d.rectangle(COUNTER_BOX, fill=COUNTER)
    d.rectangle(SINK_BOX, fill=SINK)
    d.text((TABLE_BOX[0] + 60, TABLE_BOX[3] - 22), "TABLE", fill=(250, 240, 220), font=font)
    d.text((COUNTER_BOX[0] + 50, COUNTER_BOX[3] - 22), "COUNTER", fill=(30, 30, 30), font=font)
    d.text((SINK_BOX[0] + 40, SINK_BOX[1] + 22), "SINK", fill=(240, 240, 255), font=font)
    kx, ky = keys_pos(t)
    # keys: ring + blade + label
    d.ellipse((kx - 22, ky - 14, kx - 2, ky + 6), outline=KEYS, width=5)
    d.rectangle((kx - 4, ky - 6, kx + 24, ky + 2), fill=KEYS)
    d.rectangle((kx + 14, ky + 2, kx + 18, ky + 8), fill=KEYS)
    d.text((kx - 18, ky + 8), "KEYS", fill=KEYS, font=font)
    hp = hand_pos(t)
    if hp is not None:
        hx, hy = hp
        d.rounded_rectangle((hx - 18, hy - 14, hx + 18, hy + 26), radius=10, fill=SKIN)  # palm
        for i in range(4):  # fingers reaching up-left over the keys
            d.rounded_rectangle((hx - 18 + 9 * i, hy - 30, hx - 12 + 9 * i, hy - 10), radius=3, fill=SKIN)
        d.rectangle((hx - 14, hy + 26, hx + 14, max(hy + 26, H + 40)), fill=SKIN)  # forearm to the bottom edge
    return im


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    try:
        font = ImageFont.load_default(size=16)
    except TypeError:  # older Pillow
        font = ImageFont.load_default()
    with tempfile.TemporaryDirectory() as tmp:
        n = int(DUR * FPS)
        for i in range(n):
            frame(i / FPS, font).save(Path(tmp) / f"f{i:04d}.png")
        out = OUT / "keys_on_table.webm"
        subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-framerate", str(FPS), "-i", str(Path(tmp) / "f%04d.png"),
                        "-c:v", "libvpx", "-b:v", "600k", "-pix_fmt", "yuv420p", "-g", "10", str(out)], check=True)  # fmt: skip
    (OUT / "keys_on_table.json").write_text(json.dumps({
        "video": "keys_on_table.webm", "size": [W, H], "fps": FPS, "duration_s": DUR, "object": "keys",
        "put_down_t_s": 10.0, "location": "table", "query": "Where are my keys?",
        "note": "synthetic; generated by android/tools/make_test_video.py",
    }, indent=1))
    print("wrote", out, out.stat().st_size, "bytes")


if __name__ == "__main__":
    main()
